// Generates engine/germinal-engine.js from app.html: the engine spans that
// tests/variant.test.mjs fingerprints against origin/main, copied VERBATIM
// (byte for byte), wrapped in a factory so the live wall (live.html) runs
// main's real Evolve engine. Nothing in the spans is edited; the few things
// they need from the app (the theme input, the glow set, scoring, the stats
// helpers) are provided OUTSIDE the spans by the prelude below.
//   node tools/build-engine.mjs          → rewrites engine/germinal-engine.js
//   tests/live-wall.test.mjs checks the committed file equals generate(app.html).
import fs from 'node:fs';

// Same spans, same order, as tests/variant.test.mjs (SPANS) + the two stats helpers.
export const SPANS = [['// ── Color helpers ──', '// ═══'], ['function seedCanvas(){', '// ── No paintSun()'], ['function initCells(){', '// ── Stats ──'],
  ['const PALS={', 'function buildPool(){'], ['function buildPool(){', 'function nextGen(){'], ['// ── Encode current canvas state for server ──', 'async function saveToServer(){']];
export const STATS_SPAN = ['function stabCount(){', '\n\n'];

function cut(s, a, b){ const i = s.indexOf(a); if(i < 0) throw new Error('missing ' + a); const j = s.indexOf(b, i + a.length); if(j < 0) throw new Error('missing end ' + b); return s.slice(i, j); }

// Each span is followed by its own end marker (as a comment line) so the
// test's span() finds exactly the same text in this file as in app.html.
const END = { '// ═══': '// ═══ (end of span)\n', '// ── No paintSun()': '// ── No paintSun() (end of span)\n', '// ── Stats ──': '// ── Stats ── (end of span)\n',
  'function buildPool(){': '',
  // these two end markers must start right after the span; empty stubs (never called) keep the file valid JS
  'function nextGen(){': 'function nextGen(){}   // (end of span: the app\'s nextGen is not engine code; unused stub)\n',
  'async function saveToServer(){': 'async function saveToServer(){}   // (end of span; unused stub)\n' };

export function generate(app){
  let body = '';
  for(const [a, b] of SPANS) body += cut(app, a, b) + END[b];
  body += cut(app, STATS_SPAN[0], STATS_SPAN[1]) + '\n';
  return `// GENERATED by tools/build-engine.mjs from app.html. DO NOT EDIT BY HAND.
// The engine spans below are app.html's (origin/main's engine + the approved
// full-spectrum palette table + the approved option-A save rounding), byte for
// byte; tests/live-wall.test.mjs checks them against the same fingerprints.
export function createGerminalEngine(host = {}){
  // ── prelude (not engine code): the app globals the spans use ──
  const Math = host.Math || globalThis.Math;          // tests may pass a seeded Math; browsers use the real one
  const CS=2,WC=900,WR=660,WW=WC*CS,WH=WR*CS,WT=WC*WR;
  let cells=[], generation=1, recogField=new Float32Array(WT);
  let affinityPerCell=null, userOwnedCells=new Set(), userScore=0, generationLog=[], historyLayers=[];
  const pendingSel={clear(){},add(){},delete(){},has(){return false;},size:0};   // the wall never selects: no glow
  function scoreGeneration(){}                                                  // scoring is the visitor's, not the wall's
  const document={getElementById:()=>({value:String(host.theme||'love')})};    // themePal() reads the theme input
  const btoa = globalThis.btoa, atob = globalThis.atob;
  // ── engine spans (verbatim from app.html) ──
${body}  // ── API ──
  return {
    WC, WR, WT,
    get cells(){ return cells; }, set cells(v){ cells = v; },
    get generation(){ return generation; }, set generation(v){ generation = v; },
    initCells, stepGen, stepGenFast, buildPool, buildRecogField, themePal, stabCount,
    encodeForServer, decodeFromServer, h2r, r2h, lerpH,
  };
}
`;
}

if(import.meta.url === `file://${process.argv[1]}`){
  const root = new URL('..', import.meta.url);
  const app = fs.readFileSync(new URL('app.html', root), 'utf8');
  fs.writeFileSync(new URL('engine/germinal-engine.js', root), generate(app));
  console.log('wrote engine/germinal-engine.js');
}
